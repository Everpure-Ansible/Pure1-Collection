from ansible.module_utils.basic import AnsibleModule
from ansible_collections.everpure.pure1.plugins.module_utils.pure1 import (
    filter_string,
    get_pure1,
    pure1_argument_spec,
    pure1_items,
)
import time


def generate_volumes_dict(module, pure_1):
    volumes_info = {}
    if module.params["array"]:
        array_filter = "arrays.name=" + filter_string(module.params["array"])
        volumes = pure1_items(
            module, "get_volumes", lambda: pure_1.get_volumes(filter=array_filter)
        )
    else:

        def all_volumes():
            return pure_1.get_volumes()

        volumes = pure1_items(module, "get_volumes", all_volumes)
    no_serial = 0
    for volume in range(0, len(volumes)):
        # The result is keyed on the serial number
        serial = getattr(volumes[volume], "serial", None)
        if serial is None:
            no_serial += 1
            continue
        created = getattr(volumes[volume], "created", None)
        if created is not None:
            created = time.strftime(
                "%Y-%m-%d %H:%M:%S UTC", time.gmtime(created / 1000)
            )
        arrays = [
            {"name": getattr(array, "name", None), "fqdn": getattr(array, "fqdn", None)}
            for array in getattr(volumes[volume], "arrays", None) or []
        ]
        # The array that was asked for when the volume is on it, else the first
        array = arrays[0] if arrays else {"name": None, "fqdn": None}
        if module.params["array"]:
            for candidate in arrays:
                if (candidate["name"] or "").lower() == module.params["array"].lower():
                    array = candidate
                    break
        volumes_info[serial] = {
            "id": getattr(volumes[volume], "id", None),
            "name": getattr(volumes[volume], "name", None),
            "created": created,
            "eradicated": getattr(volumes[volume], "eradicated", None),
            "destroyed": getattr(volumes[volume], "destroyed", None),
            "provisioned": getattr(volumes[volume], "provisioned", None),
            "source": [],
            "serial": serial,
            "pod": [],
            "array": dict(array),
            "arrays": arrays,
        }
        source = getattr(volumes[volume], "source", None)
        if getattr(source, "name", None) is not None:
            volumes_info[serial]["source"] = source.name
        pod = getattr(volumes[volume], "pod", None)
        if getattr(pod, "name", None) is not None:
            volumes_info[serial]["pod"] = pod.name
    if no_serial:
        module.warn(
            "Volumes left out of the result: %d without a serial number" % no_serial
        )
    return volumes_info


def main():
    argument_spec = pure1_argument_spec()
    argument_spec.update(dict(array=dict(type="str")))
    module = AnsibleModule(argument_spec, supports_check_mode=True)
    pure_1 = get_pure1(module)

    volumes = {}

    volumes["serial_numbers"] = generate_volumes_dict(module, pure_1)

    module.exit_json(changed=False, pure1_volumes=volumes)


if __name__ == "__main__":
    main()
